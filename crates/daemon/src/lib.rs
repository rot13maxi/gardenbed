//! gardenbed-daemon — the optional local tier (v0.2.md §6, D18–D19).
//!
//! One daemon per machine: a **caching gRPC proxy** over the Gardenbed RPC
//! surface plus **per-working-copy filesystem watchers** — never an owner
//! of checkout or status logic. All `.bed` writes stay in `bed`; this crate
//! never opens a working-copy index.
//!
//! Two services ride one unix socket:
//!
//! * [`proxy::ProxyService`] — implements the generated tonic `Gardenbed`
//!   trait, forwarding every RPC verbatim to the upstream server (the
//!   `repo` field rides untouched, metadata forwarded). `GetTree`/`GetBlob`
//!   are answered **cache-first** from a shared [`FsObjectStore`] at
//!   `$XDG_CACHE_HOME/gardenbed` (one store, same envelope and sharding,
//!   write-through after each upstream fetch) — which is what makes
//!   cross-working-copy dedup fall out of content addressing: a second
//!   working copy's fetch of shared content is answered from the cache and
//!   never reaches the server.
//! * [`sidecar::SidecarService`] — `Ping`, and `Register(state_dir) →
//!   generation counter`: a recursive `notify` watch on the working-copy
//!   root, excluding the state directory (`.bed`) and checkout staging
//!   entries. Every (debounced) event bumps the generation.
//!
//! Peer-uid check: before serving **write** RPCs the proxy verifies the
//! unix-socket peer's credentials (`SO_PEERCRED`) and refuses any uid other
//! than the daemon's own. Read RPCs stay open to any local peer.
//!
//! The daemon is invisible at both ends: identical outputs and on-disk
//! state whether present or absent (v0.2.md D18/D19), and `bed` falls back
//! to its embedded client whenever the socket is gone.

/// The build fingerprint: a SHA-256 over `crates/daemon/src/**` file
/// contents at build time (`build.rs`). The test harness compares it
/// against the same digest computed over the *current* sources to catch a
/// binary built from different tree state — mtime checks are blind to
/// that (`bed switch` materializes sources with commit-time mtimes;
/// dogfood finding #12's core). Mirrors `gardenbed_server::SRC_DIGEST`.
pub const SRC_DIGEST: &str = env!("GARDENBED_DAEMON_SRC_DIGEST");

/// The fingerprint carried *inside the binary's bytes*: `GARDENBED_DAEMON_
/// SRC_DIGEST:<hex>`. [`SRC_DIGEST`] is linked into any crate that reads
/// it (including the test binary), so it cannot prove which tree the
/// *located* `gardenbed-daemon` file was built from. This marker is kept
/// in the binary's rodata (referenced from `main`), where the harness
/// greps for it — a binary built from another tree carries another hex.
pub const SRC_DIGEST_MARKER: &str = concat!(
    "GARDENBED_DAEMON_SRC_DIGEST:",
    env!("GARDENBED_DAEMON_SRC_DIGEST")
);

