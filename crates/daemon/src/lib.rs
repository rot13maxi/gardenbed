#[cfg(test)]
mod tests {
    use prost::Message as _;

    #[test]
    fn sidecar_service_names_are_stable() {
        // The wire names are part of the daemon's published surface; these
        // are the strings `grpcurl`-style tools and tests address.
        let fds = std::fs::read(concat!(env!("OUT_DIR"), "/daemon.fds.bin")).unwrap();
        let set = prost_types::FileDescriptorSet::decode(fds.as_slice()).expect("fds decode");
        let file = set.file.first().expect("one compiled file");
        let svc = file
            .service
            .first()
            .expect("the sidecar service is compiled");
        assert_eq!(svc.name, Some("DaemonSidecar".into()));
        let methods: Vec<&str> = svc
            .method
            .iter()
            .map(|m| m.name.as_deref().expect("method name"))
            .collect();
        assert_eq!(methods, ["Ping", "Register", "Generation"]);
        assert_eq!(file.package, Some("gardenbed.daemon.v1".into()));
    }
}
